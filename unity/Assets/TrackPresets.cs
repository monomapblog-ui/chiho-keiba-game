/// 実在の地方競馬場をモデルにしたコース定義。
///
/// 一次情報の出典: 地方競馬全国協会(NAR)公式サイト「コース一覧」
/// (https://www.keiba.go.jp/guide/course/)および同協会発行
/// 「地方競馬総合ガイドブック2024」。
///
/// 「1周の距離」「最終直線の長さ」「コーナーの数」「1-2コーナーが3-4コーナーより
/// 小回り」などは上記の公式資料に基づく。一方、1周の中での各区間(コーナー1-2/
/// 向正面/コーナー3-4)の正確な区間割りまでは公式資料に数値の記載がないため、
/// 全体の長さ(1周距離 - 最終直線)を目安で配分した、ゲームプレイ用の推定値である。
public static class TrackPresets
{
    public static TrackData Kochi()
    {
        var t = new TrackData
        {
            TrackName = "高知競馬場",
            DistanceM = 1400f,      // 高知競馬場の実際の開催距離の一つ
            LapDistanceM = 1100f,   // 公式: 1周1100m
            LaneCount = 4,
            InnerLanePenalty = 0.3f, // 内側の砂が深く外を回る傾向がある、という特徴
        };

        // 公式: 最終直線230m。残り870m(=1100-230)を
        // 「1-2コーナー(小回り)」「向正面」「3-4コーナー(1-2よりやや緩やか)」に
        // 目安で配分(区間の正確な内訳は非公開のため推定)。
        t.CornerZones.Add(new CornerZone(0f, 200f, 1.6f));    // 1-2コーナー
        t.CornerZones.Add(new CornerZone(460f, 870f, 1.3f));  // 3-4コーナー
        // 200-460m: 向正面(バックストレッチ)
        // 870-1100m(=1周の終わり): 最終直線(公式230m)

        return t;
    }
}
